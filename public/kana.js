// ひらがな → カタカナ（ぁ〜ゖ を +0x60）。ーなどはそのまま。
export function toKatakana(text) {
  return text.replace(/[ぁ-ゖ]/g, c => String.fromCharCode(c.charCodeAt(0) + 0x60));
}
export function toHiragana(text) {
  return text.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
}

// 小書き文字（直前の字とくっつけて1つの練習単位にする）
export const SMALL_KANA = new Set([...'ぁぃぅぇぉゃゅょゎァィゥェォャュョヮ']);
// 促音（っ）は1マスの独立した字として扱う
export const SMALL_STANDALONE = new Set([...'っッ']);
export function isSmall(ch) { return SMALL_KANA.has(ch) || SMALL_STANDALONE.has(ch); }

// 自由入力の文字列を練習単位に分ける（「きゃ」は1単位、ほかは1字ずつ）。
export function splitUnits(text) {
  const units = [];
  for (const ch of text.replace(/\s+/g, '')) {
    if (SMALL_KANA.has(ch) && units.length) units[units.length - 1] += ch;
    else units.push(ch);
  }
  return units;
}
